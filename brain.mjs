/** Что строителю известно о заведении и что с ним не так. */
export function repairBrief(s, verdict, feedback) {
  const known = [
    `Заведение: ${s.name}`,
    s.town && `Город: ${s.town}`,
    s.title && `Заголовок старого сайта: ${s.title}`,
    s.description && `Описание старого сайта: ${s.description}`,
    s.hasTelLink ? "На старом сайте был телефон ссылкой tel:, но самого номера у нас нет" : null,
    s.social?.instagram && "У заведения есть Instagram",
    s.social?.facebook && "У заведения есть Facebook",
    s.menu?.mentioned && "Заведение с едой: нужно меню текстом",
  ].filter(Boolean).join("\n");

  const bad = (verdict.problems || []).map((p) => `- ${p.what} (${p.evidence})`).join("\n");

  return [
    `ЧТО ИЗВЕСТНО\n${known}`,
    `\nЧТО БЫЛО ПЛОХО НА СТАРОМ САЙТЕ (оценка ${verdict.need} из 100)\n${bad}`,
    feedback ? `\nПРЕДЫДУЩАЯ ПОПЫТКА НЕ ПОМОГЛА. Проверяющий снова нашёл:\n${feedback}\nИсправь именно это.` : "",
  ].join("\n");
}
